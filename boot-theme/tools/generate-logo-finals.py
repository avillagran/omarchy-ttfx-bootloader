#!/usr/bin/env python3
"""Encode the TTFX logo's terminal frame for every effect as logo-finals.txt.

generate-logo-finals.py CELL_DUMP OUT [--check]
CELL_DUMP is the output of final-cells (built against the vendored engine).
Every effect ends on the same full-block mask; only colours differ, so the
file holds the mask once and, per distinct colouring, a palette plus one row
of palette digits per mask row. --check fails if OUT differs.
"""
import sys

DIGITS = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"


def parse(path):
    effects, current = {}, None
    for line in open(path):
        parts = line.split()
        if parts[0] == "effect":
            name, w, h = parts[1], int(parts[2]), int(parts[3])
            assert (w, h) == (162, 20), (name, w, h)
            current = effects[name] = []
        else:
            cp, fg, flags = int(parts[0], 16), parts[1], int(parts[2], 16)
            if cp == 0x20:
                current.append(None)
            else:
                assert cp == 0x2588 and flags & 1 and fg.endswith("ff"), (cp, fg, flags)
                current.append(fg[:6])
    return effects


def encode(effects):
    masks = {tuple(c is not None for c in cells) for cells in effects.values()}
    assert len(masks) == 1, "effects end on different logo shapes"
    mask = next(iter(masks))
    groups = {}
    for name, cells in sorted(effects.items()):
        groups.setdefault(tuple(cells), []).append(name)
    out = ["# TTFX terminal frame of the Omarchy logo for every effect (generated by",
           "# boot-theme/tools/generate-logo-finals.py; do not edit). 162x20 cells,",
           "# full blocks only: '#' marks a block, then each colouring lists its",
           "# effects, its palette and one base-62 index per block (1 or 2 digits)."]
    for r in range(20):
        out.append("mask " + "".join("#" if mask[r * 162 + c] else "." for c in range(162)))
    for cells, names in sorted(groups.items(), key=lambda g: g[1][0]):
        palette = []
        for c in cells:
            if c is not None and c not in palette:
                palette.append(c)
        width = 1 if len(palette) <= len(DIGITS) else 2
        assert len(palette) <= len(DIGITS) ** width, names
        digit = (lambda i: DIGITS[i]) if width == 1 else (lambda i: DIGITS[i // 62] + DIGITS[i % 62])
        out.append("effects " + " ".join(names))
        out.append(f"palette {width} " + " ".join(palette))
        for r in range(20):
            row = "".join(digit(palette.index(c)) for c in cells[r * 162:(r + 1) * 162] if c is not None)
            out.append("row " + row)
    return "\n".join(out) + "\n"


def main():
    text = encode(parse(sys.argv[1]))
    if "--check" in sys.argv[3:]:
        if open(sys.argv[2]).read() != text:
            sys.exit(f"{sys.argv[2]} is stale: regenerate it from the vendored engine")
        print(f"{sys.argv[2]}: up to date")
        return
    with open(sys.argv[2], "w") as f:
        f.write(text)
    print(f"wrote {sys.argv[2]}")


if __name__ == "__main__":
    main()
